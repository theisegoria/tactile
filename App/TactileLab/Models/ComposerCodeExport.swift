import Foundation
import Tactile

/// Turns a composition into source code. Swift is generated here from Tactile
/// API calls; the library's planned code export (Unity, C, Unreal, Godot) can
/// register further exporters behind this protocol without touching the views.
protocol ComposerCodeExporter: Sendable {
    var id: String { get }
    var language: String { get }
    func code(for doc: ComposerDocument) -> String
}

enum ComposerExporters {
    static let all: [any ComposerCodeExporter] = [SwiftComposerExporter()]
    /// Languages the library will provide; shown disabled until then.
    static let planned = ["Unity (C#)", "C", "Unreal (C++)", "Godot (GDScript)"]
}

struct SwiftComposerExporter: ComposerCodeExporter {
    let id = "swift"
    let language = "Swift"

    func code(for doc: ComposerDocument) -> String {
        struct Step { var time: Double; var lines: [String] }
        var steps: [Step] = []
        func at(_ time: Double, _ line: String) {
            if let i = steps.firstIndex(where: { abs($0.time - time) < 0.0005 }) { steps[i].lines.append(line) }
            else { steps.append(Step(time: time, lines: [line])) }
        }
        var usesHaptics = false
        for track in doc.tracks where !track.muted {
            for event in track.events.sorted(by: { $0.start < $1.start }) {
                switch event.content {
                case .parametric(let p):
                    usesHaptics = true
                    let side = track.kind.side?.rawValue ?? "both"
                    if p.kind.isOneShot, p.repeatInterval > 0.005 {
                        var onset = event.start
                        while onset < event.end - 0.0005 {
                            at(onset, "try await controller.play(\(Self.effect(p, duration: event.duration)), side: .\(side))")
                            onset += p.repeatInterval
                        }
                    } else {
                        at(event.start, "try await controller.play(\(Self.effect(p, duration: event.duration)), side: .\(side))")
                    }
                case .audioClip(let clip):
                    usesHaptics = true
                    at(event.start, """
                    // \(track.kind.title): \(clip.displayName), trim \(Self.seconds(clip.trim)) (trim is not applied by AudioFileSource; pre-cut the file)
                    clips.append(Task { try await AudioFileSource.play(url: URL(fileURLWithPath: \(Self.quoted(clip.path))), mixer: controller.haptics, gain: \(Self.number(Double(clip.gain)))) })
                    """)
                case .rumble(let r):
                    let level = max(0, min(255, r.level))
                    let rumble = track.kind == .leftActuator ? "Rumble(left: \(level), right: 0)" : "Rumble(left: 0, right: \(level))"
                    at(event.start, "try await controller.setRumble(\(rumble))")
                    at(event.end, "try await controller.setRumble(.off)")
                case .trigger(let change):
                    for side in Self.sides(change.side) {
                        at(event.start, "try await controller.setTrigger(.\(side), try TriggerEffectSpec.\(change.design.spec).effect())")
                        at(event.end, "try await controller.setTrigger(.\(side), .off)")
                    }
                case .lightbar(let key):
                    at(event.start, "try await controller.setLightbar(LightbarColor(red: \(key.red), green: \(key.green), blue: \(key.blue)))")
                case .unsupported(let type, _):
                    at(event.start, "// Skipped unsupported event type \"\(type)\"")
                }
            }
        }
        steps.sort { $0.time < $1.time }
        var out = """
        // \(doc.name) — generated by Tactile Lab (Composer, schema \(doc.schemaVersion)).
        // Requires a connected `controller: Controller` from Tactile's ControllerManager.
        // Haptic and audio results are unverified on hardware until felt.
        import Foundation
        import Tactile

        func play\(Self.identifier(doc.name))(on controller: Controller) async throws {

        """
        if usesHaptics { out += "    try await controller.startHaptics()\n" }
        out += "    var clips: [Task<Void, any Error>] = []\n"
        out += "    let clock = ContinuousClock()\n    let start = clock.now\n"
        for step in steps {
            out += "\n    // \(Self.seconds(step.time))\n"
            if step.time > 0 { out += "    try await clock.sleep(until: start + .milliseconds(\(Int((step.time * 1000).rounded()))))\n" }
            for line in step.lines {
                for l in line.split(separator: "\n", omittingEmptySubsequences: false) { out += "    \(l)\n" }
            }
        }
        let end = max(doc.duration, doc.contentEnd)
        out += "\n    try await clock.sleep(until: start + .milliseconds(\(Int((end * 1000).rounded()))))\n"
        out += "    for clip in clips { clip.cancel() }\n"
        if usesHaptics { out += "    controller.haptics.stopAll()\n" }
        out += "    await controller.neutralize()\n}\n"
        return out
    }

    static func effect(_ p: ComposerEvent.Parametric, duration: Double) -> String {
        let a = number(Double(p.intensity)), f = number(Double(p.frequency))
        return switch p.kind {
        case .tone: ".tone(intensity: \(a), frequency: \(f), duration: \(number(duration)))"
        case .click: ".click(intensity: \(a), frequency: \(f))"
        case .detent: ".detent(intensity: \(a), frequency: \(f))"
        case .texture: ".texture(intensity: \(a), grainRate: \(number(Double(p.grainRate))), duration: \(number(duration)))"
        case .impact: ".impact(intensity: \(a))"
        }
    }

    static func sides(_ side: ComposerEvent.TriggerChange.Side) -> [String] {
        switch side { case .left: ["left"]; case .right: ["right"]; case .both: ["left", "right"] }
    }
    static func number(_ v: Double) -> String {
        let s = String(format: "%.3f", v)
        var t = s
        while t.hasSuffix("0") { t.removeLast() }
        if t.hasSuffix(".") { t.removeLast() }
        return t.isEmpty ? "0" : t
    }
    static func seconds(_ v: Double) -> String { String(format: "%.3f s", v) }
    static func quoted(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
    static func identifier(_ name: String) -> String {
        let words = name.components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty }
        let joined = words.map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
        guard let first = joined.first, first.isLetter else { return "Pattern" + joined }
        return joined
    }
}
